#!/usr/bin/env python3
"""Generate src/components/emoji_picker/subdivisions.rs from CLDR data.

ISO 3166-2 subdivision flags (emoji tag sequences like Kentucky US-KY) are not
part of RGI emoji, so the `emojis` crate does not ship them. This script builds
the table nostr.blue appends to its native emoji picker.

Pinned sources (all SPDX: Unicode-3.0, permission notice preserved below):
  - unicode-org/cldr @ release-48-2
      common/validity/subdivision.xml      canonical regular/deprecated codes
      common/subdivisions/en.xml           English subdivision names
  - unicode-org/cldr-json @ 48.2.1
      cldr-core/supplemental/subdivisionContainment.json   hierarchy

Output ordering (per country block, consumed by emoji_picker/data.rs):
  1. primary subdivisions before curated territory tails
  2. shallower containment depth first (region before county)
  3. alphabetical by name

Usage:
  python3 scripts/gen-subdivisions.py            # download to cache if needed
  python3 scripts/gen-subdivisions.py --refresh  # re-download pinned sources

The England/Scotland/Wales codes (gbeng/gbsct/gbwls) are intentionally skipped:
the `emojis` crate already ships those three RGI glyphs. Deprecated codes are
skipped (e.g. US territories usas/usgu/... which are ISO 3166-1 country flags).
"""

import argparse
import json
import re
import sys
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

CLDR_TAG = "release-48-2"
CLDR_JSON_TAG = "48.2.1"

SOURCES = {
    "validity.xml": (
        "https://raw.githubusercontent.com/unicode-org/cldr/"
        f"{CLDR_TAG}/common/validity/subdivision.xml"
    ),
    "names_en.xml": (
        "https://raw.githubusercontent.com/unicode-org/cldr/"
        f"{CLDR_TAG}/common/subdivisions/en.xml"
    ),
    "containment.json": (
        "https://raw.githubusercontent.com/unicode-org/cldr-json/"
        f"{CLDR_JSON_TAG}/cldr-json/cldr-core/supplemental/subdivisionContainment.json"
    ),
}

